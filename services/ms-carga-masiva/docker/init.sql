-- ============================================================================
-- Extensión requerida por las queries nativas (unaccent)
-- ============================================================================
CREATE EXTENSION IF NOT EXISTS unaccent;

-- ============================================================================
-- Tablas
-- ============================================================================
CREATE TABLE IF NOT EXISTS carga_interfaz (
    carint_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carint_num_usuario  VARCHAR(20)  NOT NULL,
    rut_id_rutina       VARCHAR(50)  NOT NULL,
    carint_fecha        TIMESTAMP(6) NOT NULL,
    carint_sec_archivo  INTEGER      NOT NULL,
    carint_secuencial   INTEGER      NOT NULL,
    carint_nom_path     VARCHAR(250) NOT NULL,
    carint_nom_arch     VARCHAR(250) NOT NULL,
    carint_arch_tmp     VARCHAR(10)  NOT NULL,
    carint_cadena       TEXT         NOT NULL,
    carint_estatus      CHAR(1)      NOT NULL,
    carint_mensaje      VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS catalogo_pais (
    pais_id     INTEGER      PRIMARY KEY,
    pais_nombre VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS catalogo_estado (
    estado_id     INTEGER      PRIMARY KEY,
    pais_id       INTEGER      NOT NULL,
    estado_nombre VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS catalogo_regimen_fiscal (
    reg_clave         INTEGER      PRIMARY KEY,
    reg_descripcion   VARCHAR(255),
    reg_aplica_fisica BOOLEAN,
    reg_aplica_moral  BOOLEAN
);

CREATE TABLE IF NOT EXISTS direccif (
    dif_num_contrato     VARCHAR(10)  NOT NULL,
    dif_cve_pers         VARCHAR(20)  NOT NULL,
    dif_num_pers_fid     VARCHAR(20)  NOT NULL,
    dif_recep_calle      VARCHAR(150),
    dif_recep_no_ext     VARCHAR(20),
    dif_recep_no_int     VARCHAR(20),
    dif_recep_colonia    VARCHAR(150),
    dif_recep_localidad  VARCHAR(150),
    dif_recep_municipio  VARCHAR(150),
    dif_num_pais         INTEGER,
    dif_num_estado       INTEGER,
    dif_recep_cp         VARCHAR(5),
    dif_recep_referencia VARCHAR(250),
    dif_telefono         VARCHAR(20),
    dif_mail             VARCHAR(150),
    dif_fec_alta         TIMESTAMP(6) NOT NULL,
    dif_fec_ultmod       TIMESTAMP(6) NOT NULL,
    dif_regimen_fiscal   VARCHAR(100),
    dif_nom_legal        VARCHAR(250),
    PRIMARY KEY (dif_num_contrato, dif_cve_pers, dif_num_pers_fid)
);

